    for t in FLAT_THICKNESSES:
        for w in FLAT_WIDTHS:
            if w <= t: continue
            ar = round((w * t) / 100.0, 3)
            m = round(ar * 0.785, 3)
            desig = f"{t}X{w} MM"
            sections.append({
                "id": f"flat-{t}x{w}mm",
                "designation": desig,
                "shortDesignation": desig,
                "fullDesignation": f"FLAT {t}X{w} MM",
                "normalizedDesignation": f"FLAT{t}X{w}MM",
                "family": "FLATS",
                "standard": "IS:1730",
                "massPerMetre": m,
                "area": ar,
                "dimensions": {
                    "thickness_t_mm": t,
                    "width_b_mm": w,
                    "primaryDepth": t,
                    "primaryWidth": w
                },
                "structural": {}
            })

    # =========================================================================
    # 13. HR PLATES — IS 2062:2011 / IS 1730
    # =========================================================================
    PLATE_THICKNESSES = [5, 6, 8, 10, 12, 14, 16, 18, 20, 22, 25, 28, 32]
    for t in PLATE_THICKNESSES:
        mass_sqm = round(7.85 * t, 2)
        desig = f"{t} MM"
        sections.append({
            "id": f"hr-plate-{t}mm",
            "designation": desig,
            "shortDesignation": desig,
            "fullDesignation": f"HR PLATE {t} MM",
            "normalizedDesignation": f"HRPLATE{t}MM",
            "family": "HR PLATES",
            "standard": "IS:1730",
            "massPerMetre": mass_sqm,
            "area": round(t * 10.0, 1),
            "dimensions": {
                "thickness_t_mm": t,
                "primaryDepth": t
            },
            "structural": {}
        })

    return sections


